-- 1. User Profiles Table
create table public.profiles (
  id uuid not null,
  username text null,
  country text null,
  state text null,
  city text null,
  language text null,
  updated_at timestamp with time zone null default timezone ('utc'::text, now()),
  avatar_url text null,
  constraint profiles_pkey primary key (id),
  constraint profiles_id_fkey foreign KEY (id) references auth.users (id)
) TABLESPACE pg_default;

-- 2. Sweet Potato Leave Data Table
create table public.sweet_potato_leave_data (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  temperature double precision null,
  humidity double precision null,
  light smallint null,
  soil_moisture smallint null,
  ph_value double precision null,
  malaysia_time timestamp without time zone GENERATED ALWAYS as (
    (created_at AT TIME ZONE 'Asia/Kuala_Lumpur'::text)
  ) STORED null,
  ventilation_need smallint null,
  irrigation_need smallint null,
  user_id uuid null default 'a3f12104-52fa-4834-9b75-aa159457982c'::uuid,
  plant_name text null default 'Sweet Potato Leaves'::text,
  constraint sweet_potato_leave_data_pkey primary key (id),
  constraint sweet_potato_leave_data_user_id_fkey foreign KEY (user_id) references auth.users (id) on delete CASCADE
) TABLESPACE pg_default;

-- 3. device_controls Table
create table public.device_controls (
  id bigint not null,
  pump_manual_override boolean null default false,
  fan_manual_override boolean null default false,
  automation_active boolean null default true,
  constraint device_controls_pkey primary key (id)
) TABLESPACE pg_default;

-- 4. Public Avatars Storage Bucket
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

-- 5. AI Insights Table
create table public.ai_insights (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone ('utc'::text, now()),
  crop_health_status text null,
  predicted_issue text null,
  recommended_action text null,
  health_index integer null default 100,
  growth_forecast text null,
  irrigation_status text null,
  irrigation_title text null,
  irrigation_desc text null,
  ventilation_status text null,
  ventilation_title text null,
  ventilation_desc text null,
  planting_date date null default CURRENT_DATE,
  user_id uuid null,
  constraint ai_insights_pkey primary key (id),
  constraint ai_insights_user_id_fkey foreign KEY (user_id) references auth.users (id) on delete CASCADE
) TABLESPACE pg_default;