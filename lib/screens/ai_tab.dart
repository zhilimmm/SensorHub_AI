import 'dart:convert';
import 'package:flutter/material.dart';
import 'package:http/http.dart' as http;
import 'package:supabase_flutter/supabase_flutter.dart';

class AITab extends StatefulWidget {
  final bool isLoggedIn;
  const AITab({super.key, this.isLoggedIn = true});

  @override
  State<AITab> createState() => _AITabState();
}

class _AITabState extends State<AITab> {
  bool _hasProfileData = false;
  bool _isAnalyzing = false;
  
  // State variables for AI data
  int _healthIndex = 100;
  
  String _irrigationStatus = "All Good";
  String _irrigationTitle = "Waiting for AI";
  String _irrigationDesc = "Fetching the latest insights...";
  
  String _ventilationStatus = "All Good";
  String _ventilationTitle = "Waiting for AI";
  String _ventilationDesc = "Fetching the latest insights...";

  bool get _isActive => widget.isLoggedIn && _hasProfileData;

  @override
  void initState() {
    super.initState();
    if (widget.isLoggedIn) {
      _checkProfileStatus().then((_) {
        if (_isActive) _runRandomForestInference();
      });
    }
  }

  Future<void> _checkProfileStatus() async {
    try {
      final user = Supabase.instance.client.auth.currentUser;
      if (user == null) return;
      final data = await Supabase.instance.client.from('profiles').select('username').eq('id', user.id).maybeSingle();
      if (mounted) {
        setState(() {
          _hasProfileData = data != null && data['username'] != null && data['username'].toString().trim().isNotEmpty;
        });
      }
    } catch (e) {
      debugPrint("AITab error: $e");
    }
  }

  Future<void> _runRandomForestInference() async {
    setState(() => _isAnalyzing = true);

    try {
      final sensorData = await Supabase.instance.client
          .from('sweet_potato_leave_data')
          .select('temperature, humidity, soil_moisture, ph_value')
          .order('created_at', ascending: false)
          .limit(1)
          .maybeSingle();

      // Trigger the Python FastAPI backend to run the Random Forest
      if (sensorData != null) {
        final url = Uri.parse('http://10.0.2.2:8000/api/predict');
        await http.post(
          url,
          headers: {'Content-Type': 'application/json'},
          body: jsonEncode({
            'temperature': (sensorData['temperature'] as num).toDouble(),
            'humidity': (sensorData['humidity'] as num).toDouble(),
            'soil_moisture': (sensorData['soil_moisture'] as num).toInt(),
            'ph_value': (sensorData['ph_value'] as num).toDouble(),
          }),
        );
      }

      // Fetch the FINAL text strings generated by the AI from Supabase
      final aiData = await Supabase.instance.client.from('ai_insights').select().eq('id', 1).single();

      if (mounted) {
        setState(() {
          _healthIndex = aiData['health_index'] ?? 100;
          
          _irrigationStatus = aiData['irrigation_status'] ?? 'All Good';
          _irrigationTitle = aiData['irrigation_title'] ?? 'Perfect Moisture';
          _irrigationDesc = aiData['irrigation_desc'] ?? 'The soil has just the right amount of water.';
          
          _ventilationStatus = aiData['ventilation_status'] ?? 'All Good';
          _ventilationTitle = aiData['ventilation_title'] ?? 'Great Weather';
          _ventilationDesc = aiData['ventilation_desc'] ?? 'The temperature and humidity are perfect right now.';
          
          _isAnalyzing = false;
        });
      }
    } catch (e) {
      debugPrint("AI Error: $e");
      if (mounted) {
        setState(() => _isAnalyzing = false);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Container(
      color: const Color(0xFFF5F6F7), 
      child: SafeArea(
        child: LayoutBuilder(
          builder: (context, constraints) {
            return RefreshIndicator(
              color: const Color(0xFF006947),
              onRefresh: _runRandomForestInference,
              child: SingleChildScrollView(
                physics: const AlwaysScrollableScrollPhysics(), 
                child: ConstrainedBox(
                  constraints: BoxConstraints(minHeight: constraints.maxHeight),
                  child: Padding(
                    padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 16.0),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      mainAxisAlignment: MainAxisAlignment.start,
                      children: [
                        const SizedBox(height: 16), 
                        _buildTopTitles(), 
                        const SizedBox(height: 12), 
                        _buildHealthIndexCard(), 
                        const SizedBox(height: 10), 
                        _buildRecommendationsSection(),
                        const SizedBox(height: 8), 
                      ],
                    ),
                  ),
                ),
              ),
            );
          }
        ),
      ),
    );
  }

  Widget _buildTopTitles() {
    return SizedBox(
      width: double.infinity,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.center,
        children: [
          Text(
            'SYSTEM STATUS', 
            style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, letterSpacing: 2, color: _isActive ? const Color(0xFF005A3C) : Colors.grey.shade500)
          ),
          const SizedBox(height: 6),
          Text(
            _isActive ? 'AI Helper is Active' : 'System Offline', 
            style: TextStyle(fontSize: 28, fontWeight: FontWeight.w900, color: _isActive ? const Color(0xFF022C22) : Colors.grey.shade700, height: 1.1),
            textAlign: TextAlign.center,
          ),
        ],
      ),
    );
  }

  Widget _buildHealthIndexCard() {
    // We check the strings directly to determine if everything is perfect
    bool isPerfect = (_irrigationStatus == 'All Good' && _ventilationStatus == 'All Good');

    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(18), 
      decoration: BoxDecoration(
        color: _isActive ? const Color.fromARGB(255, 150, 198, 150) : Colors.grey.shade200, 
        borderRadius: BorderRadius.circular(20),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text('Health Score', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: _isActive ? const Color(0xFF006947) : Colors.grey.shade500)),
          const SizedBox(height: 4),
          Text(
            _isActive 
              ? (isPerfect ? 'Perfect environment for plant growth for now.' : 'Some conditions are lowering the plant health score.')
              : 'System is currently offline.', 
            style: TextStyle(fontSize: 13, color: Colors.grey.shade800)
          ),
          const SizedBox(height: 12),
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            crossAxisAlignment: CrossAxisAlignment.end,
            children: [
              Row(
                crossAxisAlignment: CrossAxisAlignment.end,
                children: [
                  Text(_isActive ? '$_healthIndex' : '--', style: TextStyle(fontSize: 52, fontWeight: FontWeight.w900, color: _isActive ? const Color(0xFF2C2F30) : Colors.grey.shade400, height: 1.0)),
                  Padding(padding: const EdgeInsets.only(bottom: 6.0, left: 4.0), child: Text('%', style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold, color: _isActive ? const Color(0xFF006947) : Colors.grey.shade400))),
                ],
              ),
              if (_isActive)
                Padding(
                  padding: const EdgeInsets.only(bottom: 4.0), 
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.end,
                    mainAxisAlignment: MainAxisAlignment.end,
                    children: _buildIssueChips(),
                  ),
                )
            ],
          )
        ],
      ),
    );
  }

  List<Widget> _buildIssueChips() {
    List<Widget> chips = [];

    // Map the status back to chip colors
    if (_irrigationStatus != 'All Good') {
      chips.add(_buildChip(_irrigationTitle, _irrigationStatus == 'Warning' ? Colors.red : Colors.orange));
    }
    if (_ventilationStatus != 'All Good') {
      chips.add(_buildChip(_ventilationTitle, _ventilationStatus == 'Warning' ? Colors.red : Colors.orange));
    }

    if (chips.isEmpty) {
      chips.add(_buildChip('Perfect environment', Colors.green));
    }

    List<Widget> spacedChips = [];
    for (int i = 0; i < chips.length; i++) {
      spacedChips.add(chips[i]);
      if (i < chips.length - 1) {
        spacedChips.add(const SizedBox(height: 8));
      }
    }
    return spacedChips;
  }

  Widget _buildChip(String label, MaterialColor dotColor) {
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8), 
      decoration: BoxDecoration(
        color: Colors.white.withOpacity(0.9),
        borderRadius: BorderRadius.circular(16),
        boxShadow: [BoxShadow(color: Colors.black.withOpacity(0.05), blurRadius: 4, offset: const Offset(0, 2))]
      ),
      child: Row(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.center, 
        children: [
          Icon(Icons.circle, size: 10, color: dotColor),
          const SizedBox(width: 6),
          Text(label, style: const TextStyle(fontSize: 13, color: Colors.black87, fontWeight: FontWeight.bold, height: 1.1)),
        ],
      ),
    );
  }

  Widget _buildRecommendationsSection() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          crossAxisAlignment: CrossAxisAlignment.end,
          children: [
            Text('AI Suggestions', style: TextStyle(fontSize: 22, fontWeight: FontWeight.w900, color: _isActive ? const Color(0xFF2C2F30) : Colors.grey.shade500)),
            Text('Scikit-Learn', style: TextStyle(fontSize: 12, color: Colors.grey.shade500)),
          ],
        ),
        const SizedBox(height: 16), 
        
        if (_isAnalyzing && _isActive)
          Container(
            height: 100,
            decoration: BoxDecoration(color: Colors.white, borderRadius: BorderRadius.circular(16)),
            child: const Center(
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  CircularProgressIndicator(color: Color(0xFF006947)),
                  SizedBox(height: 12),
                  Text("Checking plants...", style: TextStyle(color: Colors.grey, fontWeight: FontWeight.bold, fontSize: 14))
                ],
              ),
            ),
          )
        else if (_isActive)
          Column(
            children: [
              _buildDynamicIrrigationCard(),
              const SizedBox(height: 16), 
              _buildDynamicVentilationCard(),
            ],
          )
      ],
    );
  }

  // Cards now just display the strings from Python/Supabase directly
  Widget _buildDynamicIrrigationCard() {
    MaterialColor color = _irrigationStatus == 'Warning' ? Colors.red : (_irrigationStatus == 'Action Needed' ? Colors.orange : Colors.blue);
    return _buildRecCard(Icons.water_drop, color, 'Watering', _irrigationStatus, _irrigationTitle, _irrigationDesc);
  }

  Widget _buildDynamicVentilationCard() {
    MaterialColor color = _ventilationStatus == 'Warning' ? Colors.red : (_ventilationStatus == 'Action Needed' ? Colors.orange : Colors.green);
    return _buildRecCard(Icons.air, color, 'Air & Temp', _ventilationStatus, _ventilationTitle, _ventilationDesc);
  }

  Widget _buildRecCard(IconData icon, MaterialColor color, String tagLabel, String tagVal, String title, String desc) {
    return Container(
      padding: const EdgeInsets.all(20), 
      decoration: BoxDecoration(color: Colors.white, borderRadius: BorderRadius.circular(16), border: Border.all(color: Colors.grey.shade200)),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Container(padding: const EdgeInsets.all(10), decoration: BoxDecoration(color: color.shade50, borderRadius: BorderRadius.circular(12)), child: Icon(icon, size: 24, color: color.shade700)),
              Column(
                crossAxisAlignment: CrossAxisAlignment.end,
                children: [
                  Text(tagLabel.toUpperCase(), style: TextStyle(fontSize: 10, fontWeight: FontWeight.bold, letterSpacing: 1, color: Colors.grey.shade400)),
                  Text(tagVal, style: TextStyle(fontSize: 14, fontWeight: FontWeight.bold, color: tagVal == 'All Good' ? color.shade700 : (tagVal == 'Warning' ? Colors.red.shade700 : Colors.orange.shade700))),
                ],
              )
            ],
          ),
          const SizedBox(height: 14), 
          Text(title, style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: const Color(0xFF2C2F30))),
          const SizedBox(height: 6), 
          Text(desc, style: TextStyle(fontSize: 14, color: Colors.grey.shade600, height: 1.4)),
        ],
      ),
    );
  }
}